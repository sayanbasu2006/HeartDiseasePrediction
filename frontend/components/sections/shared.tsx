import Link from "next/link";
import { type ReactNode } from "react";
import { Activity, ArrowUpRight, AlertCircle } from "lucide-react";
import { Button } from "@/components/ui/button";
import { assessmentScoreLabel, diseaseScore } from "@/lib/api";

export function Card({
  children,
  className = "",
}: {
  children: ReactNode;
  className?: string;
}) {
  return <section className={`card ${className}`}>{children}</section>;
}
export function ErrorBox({ message }: { message: string }) {
  return message ? (
    <div role="alert" className="error">
      <AlertCircle size={18} />
      <span>{message}</span>
    </div>
  ) : null;
}
export function Empty({
  title,
  text,
  href,
  label,
}: {
  title: string;
  text: string;
  href?: string;
  label?: string;
}) {
  return (
    <div className="empty">
      <div className="empty-icon">
        <Activity size={26} />
      </div>
      <h3>{title}</h3>
      <p>{text}</p>
      {href && (
        <Button asChild variant="outline">
          <Link href={href}>
            {label}
            <ArrowUpRight size={15} />
          </Link>
        </Button>
      )}
    </div>
  );
}
export function Loading() {
  return (
    <div className="resource-loading" role="status" aria-busy="true">
      <p>Loading research data…</p>
      <div className="skeleton-grid" aria-hidden="true">
        <i />
        <i />
        <i />
      </div>
    </div>
  );
}

export function Stat({
  title,
  value,
  sub,
  icon: Icon,
}: {
  title: string;
  value: any;
  sub: string;
  icon: any;
}) {
  return (
    <Card className="stat">
      <div className="row between">
        <span>{title}</span>
        <Icon size={18} />
      </div>
      <strong>{value}</strong>
      <small>{sub}</small>
    </Card>
  );
}
export function Score({ result }: { result: any }) {
  const score = diseaseScore(result);
  const label = assessmentScoreLabel(result.synthetic);
  return (
    <div className="score-readout">
      {(result.synthetic || result.demonstration) && (
        <span className="badge warning">
          {result.synthetic ? "Model demonstration" : "Dataset demonstration"}
        </span>
      )}
      <span className="overline">{label}</span>
      <div className="score-value">
        <strong>{(score * 10).toFixed(2)}</strong>
        <span> / 10</span>
      </div>
      <meter
        min={0}
        max={10}
        value={score * 10}
        aria-label={label}
        aria-valuetext={`${(score * 10).toFixed(2)} out of 10`}
      />
      <strong className="score-class">{result.class_description}</strong>
      <p>
        {result.synthetic
          ? "Score for an artificial label generated by the simulation."
          : "Experimental classifier score, not clinical confidence or personal medical risk."}
      </p>
    </div>
  );
}
